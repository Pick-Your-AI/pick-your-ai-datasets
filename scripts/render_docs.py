#!/usr/bin/env python3
"""Render the delivery plan, dependency register and issue bodies from canonical planning.

Generated files must not be edited by hand. --check fails when any output is stale,
missing, or when an unexpected file exists in planning/issues/.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import planlib  # noqa: E402
import validate_plan  # noqa: E402

HEADER = '<!-- Generated by scripts/render_docs.py from planning/project-backlog.json. Do not edit. -->\n'


def bullets(values):
    return [f'- {v}' for v in values]


def issue_body(item: dict, by_id: dict, backlog: dict) -> str:
    lines = [HEADER, f'**Stable ID:** `{item["id"]}` · **Record type:** {item["record_type"]} · **Workstream:** {item["workstream"]}', '',
             item['summary'], '']
    if item['record_type'] == 'Program':
        lines += [f'Coordinating parent: {backlog["external_parent"]}', '']
    children = [c for c in backlog['items'] if c['parent_id'] == item['id']]
    if children:
        lines += ['## Native children', '', *[f'- `{c["id"]}` {c["title"]}' for c in children], '']
    lines += ['## Deliverables', '', *bullets(item['deliverables']), '',
              '## Canonical artifact paths', '', *[f'- `{p}`' for p in item['artifact_paths']], '',
              '## Source and evidence requirements', '', *bullets(item['evidence_requirements']), '',
              '## Acceptance criteria', '', *[f'- [ ] {a}' for a in item['acceptance_criteria']], '',
              '## Non-goals', '', *bullets(item['non_goals']), '']
    if item['tasks']:
        lines += ['## Tasks and subtasks', '']
        for task in item['tasks']:
            lines.append(f'- [ ] `{task["id"]}` {task["title"]}')
            lines += [f'  - [ ] `{s["id"]}` {s["title"]}' for s in task['subtasks']]
        lines.append('')
    lines += ['## Dependencies', '']
    if item['blocked_by']:
        lines += [f'- Blocked by `{d}` {by_id[d]["title"]}' for d in item['blocked_by']]
    else:
        lines.append('- No prerequisite work packages.')
    dependents = [i['id'] for i in backlog['items'] if item['id'] in i['blocked_by']]
    if dependents:
        lines.append('- Blocks ' + ', '.join(f'`{d}`' for d in dependents))
    lines += ['', '## Review requirements', '', *bullets(item['review_requirements']),
              '- Approval must come from someone other than the author of the change and must cover the latest push.', '']
    lines += ['## Cross-repository handoffs', '']
    lines += [f'- {h["direction"].capitalize()}: `{h["repository"]}` — {h["artifact"]}' for h in item['handoffs']] or ['- None.']
    values = planlib.project_values(item, by_id)
    lines += ['', '## Initial planning values', '',
              f'Priority {values["Priority"]} · Readiness {values["Readiness"]} · Effort {values["Effort"]} · Release phase {values["Release Phase"]} · '
              f'Modality {values["Dataset Modality"]} · Category {values["Dataset Category"]}', '',
              'Initial values are setup defaults. Live Project triage supersedes them.']
    return '\n'.join(lines) + '\n'


def delivery_plan(backlog: dict, manifest: dict) -> str:
    c = manifest['counts']
    items = backlog['items']
    lines = [HEADER, '# Delivery plan', '',
             f'The program has **{c["Program"]} program, {c["Epic"]} epics and {c["Work Package"]} work packages** as native issues, '
             f'with **{c["tasks"]} checklist tasks and {c["subtasks"]} subtasks** and **{c["prerequisites"]} prerequisite links**. '
             f'Project [#{backlog["project"]["number"]}]({backlog["project"]["url"]}) tracks {c["project_field_values"]} initial field values.', '',
             'Planning is not implementation: every work package starts in Backlog and is accepted only through its own reviewed pull request.', '',
             '| ID | Work package | Priority | Phase | Effort | Blocked by |', '| --- | --- | --- | --- | --- | --- |']
    for item in items:
        if item['record_type'] == 'Epic':
            lines.append(f'| **{item["id"]}** | **{item["title"]}** | {item["priority"]} | {item["release_phase"]} | | |')
        elif item['record_type'] == 'Work Package':
            deps = ', '.join(item['blocked_by']) or '—'
            lines.append(f'| {item["id"]} | {item["title"]} | {item["priority"]} | {item["release_phase"]} | {item["effort"]} | {deps} |')
    return '\n'.join(lines) + '\n'


def dependencies(backlog: dict) -> str:
    items = backlog['items']
    lines = [HEADER, '# Dependencies', '',
             'A prerequisite means the dependent work package cannot be accepted until the prerequisite is accepted. '
             'Informational relationships and handoffs are not blockers. The native GitHub blocked-by links mirror this table.', '',
             '| Work package | Blocked by |', '| --- | --- |']
    lines += [f'| {i["id"]} {i["title"]} | {", ".join(i["blocked_by"])} |' for i in items if i['blocked_by']]
    lines += ['', '## Cross-repository handoffs', '', '| Work package | Direction | Repository | Artifact |', '| --- | --- | --- | --- |']
    lines += [f'| {i["id"]} | {h["direction"]} | `{h["repository"]}` | {h["artifact"]} |' for i in items for h in i['handoffs']]
    return '\n'.join(lines) + '\n'


def render(root: Path) -> dict:
    docs, errors = validate_plan.load(root)
    if not errors:
        errors = validate_plan.validate_backlog(docs['planning/project-backlog.json']) + validate_plan.validate_related(docs)
    if errors:
        raise ValueError('planning must validate before rendering: ' + '; '.join(errors[:5]))
    backlog = docs['planning/project-backlog.json']
    by_id = {i['id']: i for i in backlog['items']}
    files = {'docs/DELIVERY_PLAN.md': delivery_plan(backlog, docs['planning/release-manifest.json']),
             'docs/DEPENDENCIES.md': dependencies(backlog)}
    for item in backlog['items']:
        files[f'planning/issues/{item["id"]}.md'] = issue_body(item, by_id, backlog)
    return files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--root', type=Path, default=planlib.ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    try:
        files = render(args.root)
    except (OSError, ValueError) as exc:
        print('ERROR: ' + str(exc), file=sys.stderr)
        return 1
    stale = [p for p, text in files.items() if not (args.root / p).exists() or (args.root / p).read_text(encoding='utf-8') != text]
    unexpected = sorted(str(p.relative_to(args.root)) for p in (args.root / 'planning/issues').glob('*.md')
                        if str(p.relative_to(args.root)) not in files)
    if args.check:
        if stale or unexpected:
            print('Generated documentation is stale: ' + ', '.join(stale + unexpected), file=sys.stderr)
            return 1
        print(f'Generated documentation matches canonical planning ({len(files)} files).')
        return 0
    for path, text in files.items():
        (args.root / path).parent.mkdir(parents=True, exist_ok=True)
        (args.root / path).write_text(text, encoding='utf-8')
    for path in unexpected:
        (args.root / path).unlink()
    print(f'Rendered {len(files)} files.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
